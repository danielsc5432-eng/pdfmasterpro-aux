export const checkedCases=["signed-values.pdf","staggered-columns.pdf","mixed-sizes-blank.pdf","mixed-renderers.pdf","rotated-page.pdf","rotated-page-270.pdf","public-columns.pdf","public-annotations-rotated.pdf"];
export const reviewCases=["scanned-statement.pdf","searchable-scan.pdf","transparent-searchable-scan.pdf","skewed-low-contrast.pdf","public-lattice.pdf","public-image-overlap.pdf"];
type Result={name:string;outcome:string;ocrGroundTruth?:{passed:boolean}};
export function baselineFailures(results:Result[]):string[]{
  const failures:string[]=[],expected=new Set([...checkedCases,...reviewCases]);
  for(const name of expected){
    const rows=results.filter(row=>row.name===name);
    if(rows.length!==1){failures.push(`${name}: missing or duplicated`);continue;}
    const row=rows[0];
    if(checkedCases.includes(name)&&row.outcome!=="checked")failures.push(`${name}: approval regressed`);
    if(!["checked","review"].includes(row.outcome))failures.push(`${name}: blocked or unavailable`);
    if(row.ocrGroundTruth?.passed===false)failures.push(`${name}: known OCR content differs`);
  }
  for(const row of results)if(!expected.has(row.name))failures.push(`${row.name}: unregistered fixture`);
  return failures;
}

/** Ground truth only for images generated by our own regression fixture script. */
export function knownOcrTruth(name:string,text:string){
  if(!["scanned-statement.pdf","searchable-scan.pdf","transparent-searchable-scan.pdf","skewed-low-contrast.pdf"].includes(name))return undefined;
  const expected="SCANNED FINANCIAL STATEMENT Total 1234.56 This statement contains credit and debit details for review";
  const tokenize=(value:string)=>value.toLowerCase().match(/[a-z]+|\d+(?:[.,]\d+)*/g)??[];
  const actual=tokenize(text),wanted=tokenize(expected),remaining=[...actual];
  let matched=0;
  for(const token of wanted){const index=remaining.indexOf(token);if(index>=0){matched++;remaining.splice(index,1);}}
  const numbers=text.match(/[+\-]?\d+(?:[.,]\d+)*/g)??[];
  const valueExact=numbers.length===1&&numbers[0]==="1234.56";
  return {textCoverage:matched/wanted.length,valueExact,passed:matched===wanted.length&&valueExact};
}
